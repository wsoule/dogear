package ghsync

import (
	"bytes"
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite golden files")

func sampleProfile() Profile {
	return Profile{
		Username:    "ada",
		DisplayName: "Ada <b>Lovelace</b>",
		Bio:         "- Writes *notes* about [engines] & things &lt;3",
		Lists: []List{
			{
				Title:       "Dev Tools",
				Slug:        "dev-tools",
				Description: "Things I use_daily.",
				Entries: []Entry{
					{Title: "Go", URL: "https://go.dev/", Note: "The language"},
					{Title: "jq [cli]", URL: "https://jqlang.org/manual (v1)", Blurb: "JSON processor!"},
					{Title: "Evil", URL: "javascript:alert(1)", Note: "skip me"},
					{Title: "Mailto", URL: "mailto:a@b.c"},
					{Title: "No note", URL: "http://example.com/a_b"},
					{Title: "<script>x</script>Pipes | `ticks` #1", URL: "https://example.org/?q=a b", Note: "Line one\nline two <i>html</i>"},
				},
			},
			{Title: "Dev Tools", Slug: "dev-tools-2", Description: "", Entries: nil},
			{Title: "Café & Books!", Slug: "books", Entries: []Entry{{Title: "Dune", URL: "https://example.com/dune", Note: "Classic?"}}},
		},
		Posted: []Entry{{Title: "My post", URL: "https://example.net/post", Blurb: "A blurb"}},
	}
}

func TestRenderGolden(t *testing.T) {
	got := Render(sampleProfile())
	path := filepath.Join("testdata", "readme.golden.md")
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden (run with -update): %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("render mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
	if again := Render(sampleProfile()); !bytes.Equal(got, again) {
		t.Error("render is not deterministic")
	}
}

func TestRenderRules(t *testing.T) {
	out := string(Render(sampleProfile()))
	checks := []struct {
		name string
		ok   bool
	}{
		{"header first", strings.HasPrefix(out, "<!-- Generated by Dogear. Edits here are overwritten. -->\n")},
		{"html stripped from name", strings.Contains(out, "# Ada Lovelace\n")},
		{"javascript url skipped", !strings.Contains(out, "javascript") && !strings.Contains(out, "skip me")},
		{"mailto skipped", !strings.Contains(out, "mailto")},
		{"blurb fallback", strings.Contains(out, `- [jq \[cli\]](https://jqlang.org/manual%20%28v1%29) - JSON processor!`)},
		{"no suffix without note", strings.Contains(out, "- [No note](http://example.com/a_b)\n")},
		{"note gets period", strings.Contains(out, "- [Go](https://go.dev/) - The language.\n")},
		{"script removed", !strings.Contains(out, "<script>") && !strings.Contains(out, "<i>")},
		{"duplicate anchor", strings.Contains(out, "(#dev-tools-1)")},
		{"unicode anchor", strings.Contains(out, "(#café--books)")},
		{"posted section", strings.Contains(out, "## Everything I posted\n") && strings.Contains(out, "(#everything-i-posted)")},
		{"bio list marker escaped", strings.Contains(out, "\n\\- Writes")},
		{"entity neutralized", strings.Contains(out, "&amp;lt;3") || strings.Contains(out, `\<3`)},
	}
	for _, c := range checks {
		if !c.ok {
			t.Errorf("%s\n%s", c.name, out)
		}
	}
}

func TestRenderUsernameFallbackAndNoPosted(t *testing.T) {
	out := string(Render(Profile{Username: "bob"}))
	want := "<!-- Generated by Dogear. Edits here are overwritten. -->\n\n# bob\n"
	if out != want {
		t.Errorf("got %q want %q", out, want)
	}
	out = string(Render(Profile{Username: "bob", Posted: []Entry{{Title: "x", URL: "ftp://x"}}}))
	if strings.Contains(out, "Everything I posted") {
		t.Error("posted section rendered with no valid entries")
	}
}
