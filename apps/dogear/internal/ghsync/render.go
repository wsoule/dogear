// Package ghsync renders a user's public lists as an awesome-list README and
// keeps it in sync with a GitHub repo the user installed the Dogear GitHub App on.
package ghsync

import (
	"bytes"
	"fmt"
	"html"
	"net/url"
	"regexp"
	"strconv"
	"strings"
	"unicode"
)

// Entry is one link in a rendered list.
type Entry struct {
	Title, URL, Note, Blurb string
}

// List is one public list, rendered as its own README section.
type List struct {
	Title, Slug, Description string
	Entries                  []Entry
}

// Profile is everything the README shows for one user.
type Profile struct {
	Username, DisplayName, Bio string
	// Lists holds the public lists in owner order; the caller has already
	// filtered entries down to live, non-dead items.
	Lists []List
	// Posted is nil unless include_posted is on; the caller has already
	// excluded items that appear in a list.
	Posted []Entry
}

// generatedHeader is the first line of every README so people know not to edit it.
const generatedHeader = "<!-- Generated by Dogear. Edits here are overwritten. -->"

// postedHeading is the title of the optional final section.
const postedHeading = "Everything I posted"

// Render produces the README bytes deterministically: identical input always
// yields identical output. All user text is HTML-stripped and Markdown-escaped,
// and entries whose URL is not http(s) are dropped.
func Render(p Profile) []byte {
	var b bytes.Buffer
	anchors := newAnchorSet()

	name := cleanText(p.DisplayName)
	if name == "" {
		name = cleanText(p.Username)
	}
	b.WriteString(generatedHeader)
	b.WriteString("\n\n")
	if name != "" {
		anchors.make(name)
		fmt.Fprintf(&b, "# %s\n\n", escapeMarkdown(name))
	}
	if bio := cleanText(p.Bio); bio != "" {
		b.WriteString(escapeBlockStart(escapeMarkdown(bio)))
		b.WriteString("\n\n")
	}

	// Collect sections first so the contents list and the anchors agree.
	type section struct {
		title, anchor, description string
		lines                      []string
	}
	var sections []section
	for i, l := range p.Lists {
		title := cleanText(l.Title)
		if title == "" {
			title = cleanText(l.Slug)
		}
		if title == "" {
			title = "List " + strconv.Itoa(i+1)
		}
		sections = append(sections, section{
			title:       title,
			description: cleanText(l.Description),
			lines:       renderEntries(l.Entries),
		})
	}
	if posted := renderEntries(p.Posted); len(posted) > 0 {
		sections = append(sections, section{title: postedHeading, lines: posted})
	}

	if len(sections) > 0 {
		anchors.make("Contents")
		for i := range sections {
			sections[i].anchor = anchors.make(sections[i].title)
		}
		b.WriteString("## Contents\n\n")
		for _, s := range sections {
			fmt.Fprintf(&b, "- [%s](#%s)\n", escapeMarkdown(s.title), s.anchor)
		}
		for _, s := range sections {
			fmt.Fprintf(&b, "\n## %s\n", escapeMarkdown(s.title))
			if s.description != "" {
				b.WriteString("\n")
				b.WriteString(escapeBlockStart(escapeMarkdown(s.description)))
				b.WriteString("\n")
			}
			if len(s.lines) > 0 {
				b.WriteString("\n")
			}
			for _, line := range s.lines {
				b.WriteString(line)
				b.WriteByte('\n')
			}
		}
	}

	out := bytes.TrimRight(b.Bytes(), "\n")
	return append(out, '\n')
}

// renderEntries formats entries as "- [Title](url) - note." lines, skipping
// entries without a safe http(s) URL. The note falls back to the blurb.
func renderEntries(entries []Entry) []string {
	var lines []string
	for _, e := range entries {
		u, ok := safeURL(e.URL)
		if !ok {
			continue
		}
		title := cleanText(e.Title)
		if title == "" {
			title = u
		}
		line := fmt.Sprintf("- [%s](%s)", escapeMarkdown(title), u)
		note := cleanText(e.Note)
		if note == "" {
			note = cleanText(e.Blurb)
		}
		if note != "" {
			note = escapeMarkdown(note)
			if !strings.HasSuffix(note, ".") && !strings.HasSuffix(note, "!") && !strings.HasSuffix(note, "?") {
				note += "."
			}
			line += " - " + note
		}
		lines = append(lines, line)
	}
	return lines
}

// safeURL returns a link target that is safe to put inside Markdown link
// parentheses, or false when the URL is not an absolute http(s) URL.
func safeURL(raw string) (string, bool) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return "", false
	}
	u, err := url.Parse(raw)
	if err != nil || u.Host == "" || u.User != nil {
		return "", false
	}
	scheme := strings.ToLower(u.Scheme)
	if scheme != "http" && scheme != "https" {
		return "", false
	}
	u.Scheme = scheme
	s := u.String()
	// Characters that would end or confuse a Markdown link destination.
	s = strings.NewReplacer("(", "%28", ")", "%29", " ", "%20", "<", "%3C", ">", "%3E", "\\", "%5C").Replace(s)
	return s, true
}

var (
	scriptPattern = regexp.MustCompile(`(?is)<(script|style)\b[^>]*>.*?</(script|style)\s*>`)
	tagPattern    = regexp.MustCompile(`(?s)<[^>]*>`)
	entityPattern = regexp.MustCompile(`&(#?[A-Za-z0-9]+;)`)
)

// cleanText turns arbitrary user text into a single plain-text line: HTML
// entities are decoded, tags are removed, and whitespace runs collapse to one space.
func cleanText(s string) string {
	s = html.UnescapeString(s)
	s = scriptPattern.ReplaceAllString(s, "")
	s = tagPattern.ReplaceAllString(s, "")
	// A lone "<" without a closing ">" survives the tag pass; it is escaped later.
	s = strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, s)
	return strings.Join(strings.Fields(s), " ")
}

// markdownEscaper backslash-escapes the characters that carry Markdown or
// HTML meaning inline.
var markdownEscaper = strings.NewReplacer(
	`\`, `\\`, "[", `\[`, "]", `\]`, "(", `\(`, ")", `\)`, "*", `\*`,
	"_", `\_`, "`", "\\`", "#", `\#`, "<", `\<`, ">", `\>`, "|", `\|`,
)

// escapeMarkdown escapes inline Markdown characters and neutralizes text that
// would otherwise be read as an HTML entity (such as "&lt;").
func escapeMarkdown(s string) string {
	s = markdownEscaper.Replace(s)
	return entityPattern.ReplaceAllString(s, "&amp;$1")
}

var orderedListStart = regexp.MustCompile(`^(\d+)([.)])`)

// escapeBlockStart escapes a leading character that would turn a paragraph
// into a list, heading underline, or ordered list.
func escapeBlockStart(s string) string {
	if s == "" {
		return s
	}
	switch s[0] {
	case '-', '+', '=', '~':
		return `\` + s
	}
	return orderedListStart.ReplaceAllString(s, `$1\$2`)
}

// anchorSet generates GitHub-style heading anchors, adding -1, -2, ... to
// repeated slugs the way GitHub does.
type anchorSet struct{ seen map[string]int }

func newAnchorSet() *anchorSet { return &anchorSet{seen: map[string]int{}} }

// make returns the anchor GitHub assigns to a heading with this plain text.
func (a *anchorSet) make(text string) string {
	base := githubSlug(text)
	n, ok := a.seen[base]
	a.seen[base] = n + 1
	if !ok {
		return base
	}
	slug := base + "-" + strconv.Itoa(n)
	for {
		if _, taken := a.seen[slug]; !taken {
			a.seen[slug] = 1
			return slug
		}
		n++
		a.seen[base] = n + 1
		slug = base + "-" + strconv.Itoa(n)
	}
}

// githubSlug lowercases the text, drops punctuation, and turns spaces into
// hyphens, matching GitHub's heading anchor algorithm.
func githubSlug(text string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(text) {
		switch {
		case r == ' ':
			b.WriteByte('-')
		case r == '-' || r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r) || unicode.Is(unicode.Mn, r):
			b.WriteRune(r)
		}
	}
	return b.String()
}
